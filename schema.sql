create table if not exists public.movies (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 100),
 description text default '',
 poster_url text,
 video_url text not null,
 type text not null default 'free' check (type in ('free','paid')),
 published boolean not null default true,
 created_at timestamptz not null default now()
);
alter table public.movies enable row level security;
drop policy if exists "Public can read published movies" on public.movies;
create policy "Public can read published movies" on public.movies for select
using (published = true or (auth.jwt() ->> 'email') = 'destinyline0000@gmail.com');
drop policy if exists "Only site admin can add movies" on public.movies;
create policy "Only site admin can add movies" on public.movies for insert
with check ((auth.jwt() ->> 'email') = 'destinyline0000@gmail.com');
drop policy if exists "Only site admin can update movies" on public.movies;
create policy "Only site admin can update movies" on public.movies for update
using ((auth.jwt() ->> 'email') = 'destinyline0000@gmail.com')
with check ((auth.jwt() ->> 'email') = 'destinyline0000@gmail.com');
drop policy if exists "Only site admin can delete movies" on public.movies;
create policy "Only site admin can delete movies" on public.movies for delete
using ((auth.jwt() ->> 'email') = 'destinyline0000@gmail.com');
